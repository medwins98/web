function cleanNumber(value)
{
	if(!value) return 0;
	const clean = value.toString().replace(/\./g, '');
	return clean || 0;
}

function cleanAndFormat(value, format)
{
	value = (format === 'number' || format === 'currency') ? cleanNumber(value) : value;
	value = (format === 'date' || format === 'datetime') ? new Date(value) : value;
	
	value = (format === 'number') ? parseInt(value) : (format === 'currency') ? parseFloat(value) : value;
	return value;
}

